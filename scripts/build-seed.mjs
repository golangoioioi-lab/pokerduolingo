// Generates seed/lessons.sql (Cloudflare D1 / SQLite) from src/domain/content (catalog + lesson bodies).
// Run: npm run seed:build   (Node 24+, uses built-in TypeScript type stripping)
// Apply: npm run db:seed (remote) / npm run db:seed:local
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const lessonsDir = join(root, 'src/domain/content/lessons');
const { COURSES } = await import(pathToFileURL(join(root, 'src/domain/content/catalog.ts')).href);

const courseOf = new Map();
const tierOf = new Map();
for (const c of COURSES) for (const l of c.lessons) { courseOf.set(l.id, c.id); tierOf.set(l.id, l.tier); }

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const MAX_STATEMENT = 90_000; // D1 limit is 100 KB per statement

const statements = [];
for (const tier of ['free', 'pro']) {
  for (const file of readdirSync(join(lessonsDir, tier)).filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'))) {
    const { default: body } = await import(pathToFileURL(join(lessonsDir, tier, file)).href);
    if (!tierOf.has(body.id)) throw new Error(`${body.id}: lesson file is not in the catalog`);
    if (tierOf.get(body.id) !== tier) throw new Error(`${body.id}: folder "${tier}" does not match catalog tier "${tierOf.get(body.id)}"`);
    const sql =
      `INSERT INTO lesson_content (lesson_id, course_id, tier, blocks) VALUES (${q(body.id)}, ${q(courseOf.get(body.id))}, ${q(tier)}, ${q(JSON.stringify(body.blocks))})\n` +
      `  ON CONFLICT (lesson_id) DO UPDATE SET course_id = excluded.course_id, tier = excluded.tier, blocks = excluded.blocks, version = lesson_content.version + 1;`;
    if (sql.length > MAX_STATEMENT) throw new Error(`${body.id}: lesson too large for one D1 statement (${sql.length} bytes)`);
    statements.push(sql);
  }
}

mkdirSync(join(root, 'seed'), { recursive: true });
writeFileSync(
  join(root, 'seed/lessons.sql'),
  `-- GENERATED by scripts/build-seed.mjs — do not edit by hand.\n-- Pro rows are served by /api/lessons/:id only to users with an active entitlement.\n${statements.join('\n')}\n`,
);
console.log(`wrote seed/lessons.sql (${statements.length} lessons)`);
