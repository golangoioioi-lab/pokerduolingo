// Builds src/domain/content/catalog.ts from scripts/catalog-spec.json.
// Lessons whose body file does not exist yet are skipped (and reported), so the
// catalog can be regenerated safely while content is still being written.
// Tier = the folder the body lives in (lessons/free or lessons/pro).
// Run: npm run catalog
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const spec = JSON.parse(readFileSync(join(root, 'scripts/catalog-spec.json'), 'utf8'));
// Extra courses can live in scripts/spec-parts/*.json ({ courses, lessons }), merged in file-name order.
const partsDir = join(root, 'scripts/spec-parts');
if (existsSync(partsDir)) for (const f of readdirSync(partsDir).filter((f) => f.endsWith('.json')).sort()) {
  const part = JSON.parse(readFileSync(join(partsDir, f), 'utf8'));
  for (const c of part.courses ?? []) { if (spec.courses.some((x) => x.id === c.id)) throw new Error(`${f}: duplicate course ${c.id}`); spec.courses.push(c); }
  for (const [id, m] of Object.entries(part.lessons ?? {})) { if (spec.lessons[id]) throw new Error(`${f}: duplicate lesson id ${id}`); spec.lessons[id] = m; }
}
const lessonsDir = join(root, 'src/domain/content/lessons');

// Courses are ordered by level (stable within a level), so the learning path reads easy → hard.
const LEVEL_ORDER = ['初心者', '初級', '中級', '上級', '全レベル'];
// The play-first tutorial opens the app; then by level (stable within a level).
const FIRST = ['play-first'];
const rank = (c) => (FIRST.includes(c.id) ? -1 : LEVEL_ORDER.indexOf(c.level));
spec.courses.sort((a, b) => rank(a) - rank(b));

const missing = [];
const courses = spec.courses.map((c) => {
  const lessons = [];
  for (const id of c.lessons) {
    const meta = spec.lessons[id];
    if (!meta) throw new Error(`no metadata for lesson "${id}"`);
    const tier = existsSync(join(lessonsDir, 'free', `${id}.ts`)) ? 'free'
      : existsSync(join(lessonsDir, 'pro', `${id}.ts`)) ? 'pro' : null;
    if (!tier) { missing.push(id); continue; }
    let minutes = meta.minutes;
    if (!minutes) {
      // ~400 Japanese characters per minute of reading, plus quizzes.
      const chars = readFileSync(join(lessonsDir, tier, `${id}.ts`), 'utf8').replace(/[\x00-\x7f]/g, '').length;
      minutes = Math.min(10, Math.max(3, Math.round(chars / 400) + 1));
    }
    lessons.push({ id, title: meta.title, minutes, summary: meta.summary, tier });
  }
  const { lessons: _ids, ...rest } = c;
  return { ...rest, lessons };
}).filter((c) => c.lessons.length > 0);

writeFileSync(join(root, 'src/domain/content/catalog.ts'),
  `// GENERATED by scripts/build-catalog.mjs from scripts/catalog-spec.json — edit the spec, not this file.\n` +
  `import type { Course } from './types';\n\nexport const COURSES: Course[] = ${JSON.stringify(courses, null, 2)};\n`);

const n = courses.reduce((a, c) => a + c.lessons.length, 0);
console.log(`catalog: ${courses.length} courses, ${n} lessons` + (missing.length ? `; not yet written: ${missing.join(', ')}` : ''));
